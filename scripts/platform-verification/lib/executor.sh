#!/usr/bin/env bash
#
# ==============================================================================
# TuskerBlueprint Platform Verification Framework (TPVF)
#
# File: executor.sh
#
# Purpose:
#     Centralized execution wrappers for external CLI tools.
#
# Responsibilities:
#     - kubectl
#     - helm
#     - argocd
#     - gh
#
# All API wrappers must use these functions.
#
# shellcheck shell=bash
# ==============================================================================

set -Eeuo pipefail
IFS=$'\n\t'

################################################################################
# Kubernetes
################################################################################

kube() {

    kubectl \
        --request-timeout="${DEFAULT_REQUEST_TIMEOUT_SECONDS}s" \
        "$@"

}

################################################################################
# Helm
################################################################################

helm_exec() {

    helm "$@"

}

################################################################################
# Argo CD
################################################################################

argo() {

    argocd "$@"

}

################################################################################
# GitHub CLI
################################################################################

gh_exec() {

    gh "$@"

}
